import {PGlite} from '@electric-sql/pglite';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const db=new PGlite();
const query=await readFile(new URL('../../backend/program-preflight.sql',import.meta.url),'utf8');
const migration=await readFile(new URL('../../backend/program-upgrade.sql',import.meta.url),'utf8');
const guard=migration.slice(0,migration.indexOf('-- 01-question-history.sql'));
const inspect=async()=> (await db.query(query)).rows;
assert.equal((await inspect()).filter(r=>r['狀態']==='缺少').length,8);
await db.exec(`create schema rise_work;create schema rise_private;
create table public.rise_profiles(id int);create table public.rise_questions(id int);create table public.rise_answers(id int);
create table public.rise_question_images(id int);create table rise_work.classifications(id int);create table rise_work.entries(id int);create table rise_work.teacher_access(id int);create table public.rise_watch_sessions(id int);
create function public.rise_training_manage(text,jsonb) returns void language sql as $$select$$;
create function rise_private.teacher_student_access(uuid) returns boolean language sql as $$select false$$;`);
assert.deepEqual((await inspect()).filter(r=>r['狀態']==='缺少').map(r=>r['前置檔案']),['question-advisor.sql']);
await assert.rejects(()=>db.exec(guard),e=>e.code==='P0001'&&e.message.startsWith('Missing prerequisites: question-advisor.sql.'));
await db.exec('rollback;create table public.rise_advisor_usage(id int);');
assert.equal((await inspect()).filter(r=>r['狀態']==='缺少').length,0);
await db.exec(guard+'\ncommit;');
await db.close();console.log('PASS read-only prerequisite detection and exact missing-file guard.');
